const { app } = require('electron')
const assert = require('node:assert/strict')
const { join } = require('node:path')
const { mkdirSync, writeFileSync, existsSync } = require('node:fs')
const { execFileSync } = require('node:child_process')
const fixture = process.env.PROJECT_HUB_GIT_TEST_DIR
assert(fixture, 'Git smoke requires an isolated fixture')
assert.equal(process.env.PROJECT_HUB_DB_DIR, join(fixture, 'database'), 'Git smoke must use its own database')
assert.equal(process.env.PROJECT_HUB_GIT_SMOKE_DIR, fixture, 'Git smoke must disable user database migration')
const local = join(fixture, 'local'), remote = join(fixture, 'remote.git')
const git = args => execFileSync('git', args, { stdio: 'pipe' })
mkdirSync(local)
git(['init', '-b', 'main', local]); git(['init', '--bare', remote])
git(['-C', local, 'config', 'user.name', 'Test']); git(['-C', local, 'config', 'user.email', 'test@example.com'])
git(['-C', local, 'config', 'commit.gpgsign', 'false'])
writeFileSync(join(local, 'file.txt'), 'initial')
git(['-C', local, 'add', '.']); git(['-C', local, 'commit', '-m', 'initial'])
git(['-C', local, 'remote', 'add', 'origin', remote]); git(['-C', local, 'push', '-u', 'origin', 'main'])
git(['-C', local, 'branch', 'feature/ui-test'])
app.setPath('userData', join(fixture, 'userData'))
app.setAppPath(process.env.PROJECT_HUB_GIT_TEST_ROOT)
const timer = setTimeout(() => { console.error('Git UI smoke timed out'); app.exit(1) }, 45000)
process.on('uncaughtException', error => { console.error(error); app.exit(1) })
process.on('unhandledRejection', error => { console.error(error); app.exit(1) })
app.on('browser-window-created', (_event, win) => {
  win.show = () => {}
  win.webContents.setBackgroundThrottling(false)
  win.webContents.once('did-finish-load', async () => {
    const evaluate = code => win.webContents.executeJavaScript(code, true)
    const waitFor = async code => {
      const deadline = Date.now() + 7000
      while (!await evaluate(code)) {
        if (Date.now() > deadline) throw new Error('UI condition timed out: ' + code)
        await new Promise(resolve => setTimeout(resolve, 50))
      }
    }
    try {
      const project = await evaluate(`(async () => {
        const workspaces = await window.api.workspace.list()
        return window.api.project.add({ workspace_id: workspaces[0].id, name: 'Git live test', path: ${JSON.stringify(local)} })
      })()`)
      const databasePath = join(fixture, 'database', 'project-hub.db')
      assert(existsSync(databasePath), 'Application must create the isolated test database')
      const isolatedDb = new (require('better-sqlite3'))(databasePath, { readonly: true })
      try {
        assert.equal(isolatedDb.prepare('SELECT name FROM project WHERE id = ?').get(project.id)?.name, 'Git live test')
        assert.equal(isolatedDb.prepare('SELECT COUNT(*) AS count FROM project').get().count, 1, 'Fixture must not import user projects')
      } finally { isolatedDb.close() }
      await evaluate(`location.hash = ${JSON.stringify('#/projects/' + project.id)}`)
      await waitFor(`document.body.innerText.includes('文件变更')`)
      const screenshot = async name => {
        if (!process.env.PROJECT_HUB_GIT_SCREENSHOT_DIR) return
        mkdirSync(process.env.PROJECT_HUB_GIT_SCREENSHOT_DIR, { recursive: true })
        await evaluate(`document.querySelector('.git-workspace').scrollIntoView({ block: 'start' })`)
        await waitFor(`!document.querySelector('.el-loading-mask') && !document.querySelector('.page-fade-enter-active')`)
        await evaluate(`new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))`)
        await new Promise(resolve => setTimeout(resolve, 250))
        const rect = await evaluate(`(() => { const r = document.querySelector('.git-workspace').getBoundingClientRect(); return {x: Math.max(0, Math.round(r.x)), y: Math.max(0, Math.round(r.y)), width: Math.round(r.width), height: Math.min(Math.round(r.height), innerHeight - Math.max(0, Math.round(r.y)))} })()`)
        writeFileSync(join(process.env.PROJECT_HUB_GIT_SCREENSHOT_DIR, name + '.png'), (await win.capturePage(rect)).toPNG())
      }
      await screenshot('git-ui-clean')
      await evaluate(`(() => {
        const input = document.querySelector('textarea[placeholder^="提交说明"]')
        input.value = 'preserved draft'
        input.dispatchEvent(new Event('input', { bubbles: true }))
      })()`)
      writeFileSync(join(local, 'file.txt'), 'external save')
      await waitFor(`document.querySelector('.changes-unstaged .changes-list')?.innerText.includes('file.txt') && !document.querySelector('.changes-staged .changes-list')`)
      assert.equal(await evaluate(`document.querySelector('textarea[placeholder^="提交说明"]').value`), 'preserved draft')
      git(['-C', local, 'add', '.'])
      await waitFor(`document.querySelector('.changes-staged .changes-list')?.innerText.includes('file.txt') && !document.querySelector('.changes-unstaged .changes-list')`)
      writeFileSync(join(local, 'file.txt'), 'changed after staging')
      await waitFor(`document.querySelector('.changes-staged .changes-list')?.innerText.includes('file.txt') && document.querySelector('.changes-unstaged .changes-list')?.innerText.includes('file.txt')`)
      await screenshot('git-ui-changes')
      git(['-C', local, 'add', '.']); git(['-C', local, 'commit', '-m', 'external pending commit'])
      await waitFor(`document.querySelector('.el-tab-pane .commit-list')?.innerText.includes('external pending commit') && !document.querySelector('.changes-list')`)
      await screenshot('git-ui-pending')
      git(['-C', local, 'push'])
      await waitFor(`!document.querySelector('.el-tab-pane .commit-list') && document.querySelector('.el-tab-pane')?.innerText.includes('没有待推送提交')`)
      assert.equal(await evaluate(`document.querySelector('textarea[placeholder^="提交说明"]').value`), 'preserved draft')
      await evaluate(`document.querySelector('.git-branch-select .el-select__wrapper').click()`)
      await waitFor(`Array.from(document.querySelectorAll('.el-select-dropdown__item')).some(el => el.innerText.trim() === 'feature/ui-test')`)
      await evaluate(`Array.from(document.querySelectorAll('.el-select-dropdown__item')).find(el => el.innerText.trim() === 'feature/ui-test').click()`)
      await waitFor(`document.querySelector('.git-branch-select').innerText.includes('feature/ui-test') && !document.querySelector('.git-branch-select .is-disabled')`)
      assert.equal(execFileSync('git', ['-C', local, 'branch', '--show-current'], { encoding: 'utf8' }).trim(), 'feature/ui-test')
      await evaluate(`Array.from(document.querySelectorAll('.git-toolbar button')).find(el => el.innerText.trim() === '新建分支').click()`)
      await waitFor(`document.querySelector('input[placeholder^="分支名称"]')`)
      await evaluate(`(() => { const input = document.querySelector('input[placeholder^="分支名称"]'); input.value = 'feature/new-ui'; input.dispatchEvent(new Event('input', {bubbles:true})) })()`)
      await evaluate(`Array.from(document.querySelectorAll('.el-dialog button')).find(el => el.innerText.trim() === '创建并切换').click()`)
      await waitFor(`document.querySelector('.git-branch-select').innerText.includes('feature/new-ui') && !document.querySelector('.git-branch-select .is-disabled')`)
      assert.equal(execFileSync('git', ['-C', local, 'branch', '--show-current'], { encoding: 'utf8' }).trim(), 'feature/new-ui')
      assert.equal(await evaluate(`document.querySelector('textarea[placeholder^="提交说明"]').value`), 'preserved draft')
      await evaluate(`location.hash = '#/projects'`)
      await waitFor(`!document.querySelector('textarea[placeholder^="提交说明"]')`)
      await waitFor(`document.querySelector('.project-git-status')?.innerText.includes('无变更')`)
      writeFileSync(join(local, 'file.txt'), 'unpublished commit')
      git(['-C', local, 'add', '.']); git(['-C', local, 'commit', '-m', 'list pending commit'])
      writeFileSync(join(local, 'file.txt'), 'uncommitted modification')
      writeFileSync(join(local, 'new.txt'), 'untracked file')
      await waitFor(`(() => { const status = document.querySelector('.project-git-status'); return status?.querySelector('.modified')?.innerText.includes('1') && status.querySelector('.untracked')?.innerText.includes('1') && status.querySelector('.unpushed')?.innerText.includes('1') })()`)
      assert(await evaluate(`(() => { const menu = document.querySelector('.cell-actions .el-dropdown button').getBoundingClientRect(); const table = document.querySelector('.el-table').getBoundingClientRect(); return menu.right <= table.right + 1 && menu.left >= table.left })()`), 'Row menu must remain visible when all three statuses are present')
      if (process.env.PROJECT_HUB_GIT_SCREENSHOT_DIR) {
        await waitFor(`!document.querySelector('.page-fade-enter-active, .page-fade-leave-active')`)
        await evaluate(`new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))`)
        await new Promise(resolve => setTimeout(resolve, 250))
        const rect = await evaluate(`(() => { const r = document.querySelector('.project-management-page').getBoundingClientRect(); return {x: Math.round(r.x), y: Math.round(r.y), width: Math.round(r.width), height: Math.round(r.height)} })()`)
        writeFileSync(join(process.env.PROJECT_HUB_GIT_SCREENSHOT_DIR, 'git-list-status.png'), (await win.capturePage(rect)).toPNG())
      }
      assert(!await evaluate(`Array.from(document.querySelectorAll('.cell-actions button')).some(el => el.innerText.trim() === '运行')`))
      await evaluate(`document.querySelector('.cell-actions .el-dropdown button').click()`)
      await waitFor(`Array.from(document.querySelectorAll('.el-dropdown-menu__item')).some(el => el.innerText.trim() === '运行项目')`)
      await evaluate(`Array.from(document.querySelectorAll('.el-dropdown-menu__item')).find(el => el.innerText.trim() === '运行项目').click()`)
      await waitFor(`document.querySelector('.el-dialog__title')?.innerText === '选择运行命令'`)
      await evaluate(`document.querySelector('.el-dialog__headerbtn').click()`)
      await evaluate(`document.querySelector('input[value="card"]').click()`)
      await waitFor(`document.querySelector('.project-card .project-git-status .untracked')?.innerText.includes('1')`)
      git(['-C', local, 'add', '.'])
      await waitFor(`!document.querySelector('.project-card .project-git-status .untracked') && document.querySelector('.project-card .project-git-status .modified')?.innerText.includes('2')`)
      git(['-C', local, 'commit', '-m', 'commit list changes']); git(['-C', local, 'push', '-u', 'origin', 'HEAD'])
      await waitFor(`document.querySelector('.project-card .project-git-status')?.innerText.includes('无变更')`)
      clearTimeout(timer)
      console.log('Built Electron Git UI: detail and list live status, table/card views, run menu, branch switch/create passed; isolated database verified')
      app.quit()
    } catch (error) { console.error(error); app.exit(1) }
  })
})
require(join(process.env.PROJECT_HUB_GIT_TEST_ROOT, 'out/main/index.js'))
